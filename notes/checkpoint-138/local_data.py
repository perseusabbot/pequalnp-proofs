"""Generate the finite local incidence tables and the symmetry words used by Lean."""
import argparse
import ast
from collections import deque
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent/'checkpoint-137'))
from rectangles import ROWS, bits, require, six_rectangles


def upstream_actions(source, name):
    text = source.split('def '+name+' : Array (Array ',1)[1].split(':=',1)[1].lstrip()
    return ast.literal_eval(text[:text.index(']]')+2].replace('#',''))


def tables(upstream):
    source = (upstream/'lean/PEqualNP/Outside/L_meta_9338.lean').read_text()
    rows,cols,ids = [upstream_actions(source,n) for n in ['genRows','genCols','genLabels']]
    boxes = six_rectangles()
    masks = [sum(b << (21*i) for i in bits(a)) for a,b in boxes]
    cells = [21*i+j for i,w in enumerate(ROWS) for j in bits(w)]
    generators = [(h,[21*p[i//21]+q[i%21] for i in range(441)]) for p,q,h in zip(rows,cols,ids)]
    inverse = [([h.index(j) for j in range(168)],[v.index(j) for j in range(441)])
               for h,v in generators]
    # Reverse breadth-first paths yield forward words to each representative.
    left = {z for z in cells if not (masks[0] >> z & 1)}
    routes,roots = {},[]
    while left:
        root = min(left)
        k = len(roots)
        roots.append(root)
        seen = {(0,root):()}
        queue = deque(seen)
        while queue:
            h,z = queue.popleft()
            for i,(a,b) in enumerate(inverse):
                dest = (a[h],b[z])
                if dest not in seen:
                    seen[dest] = (i,*seen[h,z])
                    queue.append(dest)
        for z in list(left):
            if (0,z) in seen:
                routes[z] = k,seen[0,z]
                left.remove(z)
    require(roots == [2,23,33] and len(routes) == 300,'Wrong pair orbit inventory')
    sites = list(bits(masks[0]))
    through = [[j for j,m in enumerate(masks) if m >> z & 1] for z in roots]
    require(len(sites) == 36 and all(len(s)==18 for s in through),'Wrong local size')
    restricted = [[sum(((masks[j]>>v)&1)<<i for i,v in enumerate(sites)) for j in hs] for hs in through]
    def point(v):
        return '('+str(v//21)+','+str(v%21)+')'
    def row(seq):
        return '#['+','.join(map(str,seq))+']'
    routes_text = []
    for z in range(441):
        k,word = routes.get(z,(0,()))
        routes_text.append('('+str(k)+',['+','.join(map(str,word))+'])')
    def array_lines(seq, width):
        return '#[\n  '+',\n  '.join(','.join(seq[i:i+width]) for i in range(0,len(seq),width))+']'
    return f'''-- Generated by local_data.py from the pinned upstream board and its nine checked maps.
import Board

namespace Checkpoint138

open PEqualNP.Outside.L_meta_9338

def roots : Array Cell := {row(map(point,roots))}
def sites : Array Cell := {row(map(point,sites))}
def throughIds : Array (Array H) := {row(row(xs) for xs in through)}
def localMasks : Array (Array Nat) := {row(row(xs) for xs in restricted)}
def routeTable : Array (Fin 3 × List G) := {array_lines(routes_text,7)}

def root (t : Fin 3) : Cell := roots[t.val]!
def site (i : Fin 36) : Cell := sites[i.val]!
def alt (t : Fin 3) (j : Fin 18) : H := throughIds[t.val]![j.val]!
def mask (t : Fin 3) (j : Fin 18) : Nat := localMasks[t.val]![j.val]!
def route (x : Cell) := routeTable[21*x.1.val+x.2.val]!

set_option maxHeartbeats 0 in
theorem routeOK : ∀ z : Cell, bit z.1 z.2 = false → ¬ Inc z 0 →
    walk (route z).2 0 = 0 ∧ moveCells (route z).2 z = root (route z).1 := by
  decide +kernel

set_option maxHeartbeats 0 in
theorem sitesOK : ∀ z : Cell, Inc z 0 → ∃ j : Fin 36, site j = z := by
  decide +kernel

set_option maxHeartbeats 0 in
theorem idsOK : ∀ (t : Fin 3) (h : H), Inc (root t) h → ∃ j : Fin 18, alt t j = h := by
  decide +kernel

set_option maxHeartbeats 0 in
theorem masksOK : ∀ (t : Fin 3) (j : Fin 18) (i : Fin 36),
    (mask t j).testBit i.val = true ↔ Inc (site i) (alt t j) := by
  decide +kernel

#print axioms routeOK
#print axioms sitesOK
#print axioms idsOK
#print axioms masksOK

end Checkpoint138
'''


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('upstream',type=Path)
    ap.add_argument('--output',type=Path)
    args = ap.parse_args()
    generated = tables(args.upstream)
    if args.output:
        args.output.write_text(generated)
    else:
        require(generated == (HERE/'src/LocalData.lean').read_text(),'Lean tables differ')
        print('The three local tables and all 300 normalization words match.')
